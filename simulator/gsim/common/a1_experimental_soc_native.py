#!/usr/bin/env python3
"""One real experimental A1 platform, bounded native independent-clock acceptance.

Three immutable phases: two production CHIRRTL structures; one full runtime SV
build; one positive and one actual DDR-data negative using that same model.
No default promotion, virtual M3 coverage, rate transition, board or timing claim.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re
import shlex
import subprocess
import tarfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PROFILE = 'full-r1-m3'


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


base = load('native_epoch_tools', HERE / 'i1_msi_epoch_native.py')
identity = load('experimental_cpu_identity', ROOT / 'fpga/common/cpu_identity.py')


def require(ok, message):
    if not ok:
        raise RuntimeError(message)


def sha(path):
    return base.sha(Path(path))


def compile_source_paths():
    result = []
    for directory in ('src/main/scala', 'src/test/scala', 'third_party/berkeley-hardfloat/src/main/scala'):
        result += list((ROOT / directory).rglob('*.scala'))
    for directory in ('src/main/resources', 'src/test/resources', 'compile-resources',
                      'third_party/berkeley-hardfloat/src/main/resources',
                      'third_party/berkeley-hardfloat/compile-resources'):
        result += [p for p in (ROOT / directory).rglob('*') if p.is_file()]
    result += [ROOT / name for name in ('build.mill', '.mill-version', '.mill-jvm-opts')]
    return sorted(set(result))


def source_paths():
    result = compile_source_paths()
    result += [Path(__file__), HERE / 'a1_experimental_soc_tb.sv',
               HERE / 'a1_dynamic_roundtrip_tb.sv', HERE / 'a1_dynamic_roundtrip.S',
               HERE / 'i1_runtime_network.ld', HERE / 'i1_msi_epoch_native.py',
               ROOT / 'fpga/common/cpu_identity.py', ROOT / 'simulator/cdc/rtl8211f_pin_model.sv']
    result += [ROOT / 'fpga/common/dynamic' / (name + '.sv') for name in
               ('behavioral_primitives', 'native_clock_gate', 'native_clock_drp', 'native_dynamic_clock_domain')]
    return sorted(set(result))


def current_classpath():
    # Generated by the explicit post-compile `mill show IonSoC.test.runClasspath`.
    values = json.loads((ROOT / 'out/IonSoC/test/runClasspath.json').read_text())['value']
    entries = [str(Path(value.split(':', 3)[3]).resolve()) for value in values]
    files = []
    for entry in entries:
        path = Path(entry)
        if path.is_dir():
            files += [p for p in path.rglob('*') if p.is_file()]
        elif path.is_file():
            files.append(path)
    return entries, file_map(sorted(set(files)))


def verify_compile_receipt(path):
    receipt = json.loads(path.read_text())
    require(receipt.get('schema') == 'valence-scala-compile-v1' and type(receipt.get('exit')) is int and
            receipt['exit'] == 0, 'complete successful bound compile receipt required; legacy exit-only rejected')
    require(receipt.get('sourceRoot') == str(ROOT), 'compile source root mismatch')
    commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    require(receipt.get('sourceCommit') == commit, 'compile source commit mismatch')
    expected = file_map(compile_source_paths())
    require(receipt.get('sourceInputs') == expected, 'compile source set/hash mismatch')
    manifest = receipt.get('sourceManifest', {})
    require(set(manifest) == {'path', 'sha256'}, 'compile source manifest binding missing')
    require(sha(manifest['path']) == manifest['sha256'] and
            json.loads(Path(manifest['path']).read_text()) == expected, 'compile source manifest mismatch')
    entries, classes = current_classpath()
    require(receipt.get('runClasspathEntries') == entries and receipt.get('compiledClasspath') == classes,
            'post-compile runtime classpath set/hash mismatch')
    require(classes, 'empty compiled classpath')
    return receipt


def source_hashes():
    return {str(p.relative_to(ROOT)): sha(p) for p in source_paths()}


def file_map(paths):
    return {str(p.resolve()): sha(p) for p in paths}


def verify_files(entries):
    for path, expected in entries.items():
        require(Path(path).is_file() and sha(path) == expected, 'artifact/source drift: ' + path)


def tool_hashes(tools):
    result = base.tool_hashes(tools)
    vvp = tools['vvp']
    if vvp.read_bytes()[:2] == b'#!':
        for line in vvp.read_text().splitlines():
            if line.startswith('exec '):
                words = shlex.split(line)
                if len(words) > 1 and Path(words[1]).is_file():
                    result['vvp_engine'] = dict(path=words[1], sha256=sha(words[1]))
                if '-M' in words:
                    directory = Path(words[words.index('-M') + 1])
                    for module in sorted(directory.glob('*.vpi')):
                        result['vvp_module_' + module.name] = dict(path=str(module), sha256=sha(module))
    return result


def exact_fields(product, expected, label):
    for key, value in expected.items():
        require(product.get(key) == value, label + '.' + key + ' != ' + repr(value))


def check_identity(value, profile, runtime):
    identity.validate(value, 'a1', profile)
    # Independent serialization, rather than trusting only the shared verifier.
    payload = {k: v for k, v in value.items() if k != 'identitySha256'}
    digest = hashlib.sha256(json.dumps(payload, sort_keys=True, separators=(',', ':'),
                                      ensure_ascii=False, allow_nan=False).encode()).hexdigest()
    require(digest == value['identitySha256'], 'independent canonical identity digest mismatch')
    require(value['runtimeMode'] == ('experimental-a1-runtime' if runtime else 'static'), 'runtime mode mismatch')
    require(value['clockProfile'] == ('boot50-static' if runtime else 'production'), 'clock profile mismatch')
    exact_fields(value['nominalClocks'], dict(cpuHz='50000000' if runtime else '100000000',
        fabricHz='50000000' if runtime else '250000000', timebaseHz='250000000', ddrUiHz='250000000',
        aonHz='50000000', uartHz='50000000'), 'nominalClocks')
    exact_fields(value['boundary'], dict(homeAcquireEntries='2', homeWritebackEntries='2', scalarOwnerBits='4',
        maintenanceEpochBits='8', **{key: str(runtime).lower() for key in
        ('runtimeMaintenance', 'runtimeCancellation', 'runtimeInterruptHold')}), 'boundary')
    exact_fields(value['boundary']['coherent'], dict(addrWidth='64', dataWidth='64', sourceBits='3', sinkBits='1'), 'TL')
    for key in ('effectiveConfig', 'sharedFabricConfig'):
        derived = value[key]['_derived']
        exact_fields(derived, dict(isaProfile='rv64gc', issueWidth='2', ramBase=str(0x80200000),
            ddrBytes=str(0x80000000), cacheLineBytes='64', instructionCacheLines='512',
            dataCacheLines='512', cacheWays='2'), key)
        exact_fields(derived['ddr'], dict(maxOutstanding='4', maxOutstandingWrites='2'), key + '.ddr')
    core = value['effectiveCore']
    exact_fields(core, dict(robEntries='16', physicalRegs='48', renameWidth='2', commitWidth='2',
        completionWidth='2', pmpEntries='16', virtualMemoryLevels='3', compressedInstructions='true',
        machineSystem='true', atomicMemory='true', advertiseFloatingPoint='true'), 'core')
    exact_fields(core['floatingPoint'], {key: 'true' for key in ('f', 'd', 'addSubtract', 'multiply', 'divide',
        'squareRoot', 'fusedMultiplyAdd', 'compareMinMax', 'signClassMove', 'conversions', 'memory')}, 'FP')
    if profile == PROFILE:
        exact_fields(value['effectiveConfig'], dict(virtualRamLoadPrecheck='true', canonicalVirtualStoreOverlap='true',
            independentDemandAdmission='true', internalLineGrant='true'), 'candidate')
    return value


def fir_graph(path):
    text = path.read_text()
    matches = list(re.finditer(r'^  (?:(?:public|private) )?(?:module|extmodule|intmodule) (\w+)\s*:', text, re.M))
    modules = {}
    for index, match in enumerate(matches):
        body = text[match.end():matches[index + 1].start() if index + 1 < len(matches) else len(text)]
        modules[match.group(1)] = re.findall(r'^\s+inst (\w+) of (\w+)', body, re.M)
    require('CommonMachinePlatform' in modules, 'missing real CommonMachinePlatform top')
    reachable, pending = set(), ['CommonMachinePlatform']
    while pending:
        module = pending.pop()
        if module in reachable:
            continue
        reachable.add(module)
        pending += [child for _, child in modules.get(module, [])]
    for name in ('CommonA1CpuTile', 'CommonCpuClockBoundary', 'CommonMachineFabric', 'ParallelLoadStoreUnit',
                 'MixedCoherentLineHome', 'HeldResponseCdcDataFifo', 'FloatingPointState'):
        require(name in reachable, 'missing actual connected module: ' + name)
    return dict(module_count=len(modules), reachable_modules=sorted(reachable),
                lsu_slots=sum(child.startswith('LoadStoreUnit') for _, child in modules['ParallelLoadStoreUnit']),
                top_instances=modules['CommonMachinePlatform'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--phase', required=True, choices=('structures', 'build', 'run'))
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--sv2v', required=True)
    parser.add_argument('--compile-receipt', type=Path, required=True)
    parser.add_argument('--previous-receipt', type=Path)
    args = parser.parse_args()
    out = args.out.resolve()
    require(not out.exists(), 'fresh phase output required')
    out.mkdir(parents=True)
    compile_receipt = args.compile_receipt.resolve()
    compile_binding = verify_compile_receipt(compile_receipt)
    tools = {name: base.tool(value) for name, value in (('mill', 'mill'), ('sv2v', args.sv2v),
        ('iverilog', 'iverilog'), ('vvp', 'vvp'), ('gcc', 'riscv64-unknown-elf-gcc'),
        ('objcopy', 'riscv64-unknown-elf-objcopy'), ('nm', 'riscv64-unknown-elf-nm'))}
    record = dict(status='RUNNING', phase=args.phase,
        source_commit=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        source_sha256=source_hashes(), tools=tool_hashes(tools), cases=[], artifacts={},
        compile_receipt=file_map([compile_receipt]), compile_binding=compile_binding, profile=PROFILE,
        scope='real full CommonMachinePlatform integration; one Bare-M DDR/MMIO telemetry smoke',
        not_claimed=['M3 virtual-store forwarding in this Bare guest', 'full ISA regression',
            'runtime clock-rate transition', 'PHY/drain qualification', 'board qualification',
            'PPA/Fmax/300MHz', 'hardware performance from host elapsed time'])
    (out / 'source-manifest.json').write_text(json.dumps(record['source_sha256'], indent=2) + '\n')
    with tarfile.open(out / 'frozen-inputs.tar.gz', 'w:gz') as archive:
        for path in source_paths():
            archive.add(path, arcname=str(path.relative_to(ROOT)), recursive=False)
    require(source_hashes() == record['source_sha256'], 'source drift while freezing inputs')
    record['frozen_inputs'] = file_map([out / 'source-manifest.json', out / 'frozen-inputs.tar.gz'])

    def run(command, name, timeout):
        verify_compile_receipt(compile_receipt)
        code, log = base.run(command, out, name, timeout, record)
        require(code == 0, name + ' failed: ' + log[-2500:])
        verify_compile_receipt(compile_receipt)
        return log

    def previous(status):
        require(args.previous_receipt is not None, 'previous phase receipt required')
        path = args.previous_receipt.resolve()
        old = json.loads(path.read_text())
        require(old['status'] == status, 'previous phase did not pass')
        require(old['source_sha256'] == record['source_sha256'], 'source changed between phases')
        require(old['tools'] == record['tools'], 'tool changed between phases')
        require(old['compile_receipt'] == record['compile_receipt'], 'compile receipt changed between phases')
        verify_files(old['artifacts'])
        verify_files(old['compile_receipt'])
        record['previous_receipt'] = file_map([path])
        return old

    try:
        if args.phase == 'structures':
            records = {}
            for profile in ('selected', PROFILE):
                directory = out / profile
                command = [tools['mill'], '-i', 'IonSoC.test.runMain', 'platform.CommonMachinePlatformMain',
                    directory, 'a1', '--compile-receipt=' + str(compile_receipt), '--vivado-memories', '--emit-chirrtl-only']
                if profile != 'selected':
                    command += ['--experimental-a1-profile=' + profile]
                run(command, 'emit-' + profile, 600)
                emission = json.loads((directory / 'emission-profile.json').read_text())
                value = json.loads((directory / 'microarchitecture-identity.json').read_text())
                require(emission['cpuMicroarchitecture'] == value, 'standalone/emission identity differs')
                identity.validate_emission(emission, profile)
                check_identity(value, profile, False)
                exact_fields(emission, dict(rtlFormat='CHIRRTL', top='CommonMachinePlatform', cpu='a1',
                    cpuClockHz=100000000, fabricClockHz=250000000, romBytes=131072, instructionCacheBytes=32768,
                    dataCacheBytes=32768, cacheWays=2, homeClients=2, homeLines=1024, homeWays=4,
                    homeAcquireEntries=2, homeWritebackEntries=2, ddrSlots=4, ddrWriteSlots=2,
                    fifoDepth=16, heldFifo='HeldResponseCdcDataFifo', triSpeedEthernet=True,
                    triSpeedTxFrameSlots=2, jtagDmiAddressBits=7, physicalTimingVerified=False, boardVerified=False), 'emission')
                verify_files(emission['sources']); verify_files(emission['compiledClasspath']); verify_files(emission['artifacts'])
                firs = sorted(directory.glob('*.fir'))
                require(len(firs) == 1, 'one complete CHIRRTL required')
                graph = fir_graph(firs[0])
                require(graph['lsu_slots'] == (4 if profile == PROFILE else 2), 'actual ParallelLSU slot count mismatch')
                for module in ('CompletedCanonicalStoreForwarding', 'BranchResolutionMailbox', 'CircularFetchInstructionStorage'):
                    require((module in graph['reachable_modules']) == (profile == PROFILE), 'actual selector module mismatch: ' + module)
                records[profile] = dict(identity=value, graph=graph, emission_sha256=sha(directory / 'emission-profile.json'))
            require(records['selected']['identity']['sharedFabricConfig'] == records[PROFILE]['identity']['sharedFabricConfig'],
                    'shared fabric configuration changed with CPU-private selector')
            require(records['selected']['identity']['boundary'] == records[PROFILE]['identity']['boundary'], 'transport boundary changed')
            try:
                identity.check_reuse(records[PROFILE]['identity'], records['selected']['identity'])
            except ValueError as exc:
                record['cross_selector_reuse_rejected'] = str(exc)
            else:
                raise RuntimeError('same-source old selected identity was accepted as candidate cache')
            record['structures'] = records
            record['status'] = 'PASS_REAL_PLATFORM_STRUCTURES'
        elif args.phase == 'build':
            old = previous('PASS_REAL_PLATFORM_STRUCTURES')
            run([tools['gcc'], '-march=rv64ima_zicsr_zifencei', '-mabi=lp64', '-mcmodel=medany', '-mno-relax',
                '-nostdlib', '-nostartfiles', '-Wl,--no-relax', '-T' + str(HERE / 'i1_runtime_network.ld'),
                HERE / 'a1_dynamic_roundtrip.S', '-o', out / 'guest.elf'], 'guest-build', 60)
            run([tools['objcopy'], '-O', 'binary', out / 'guest.elf', out / 'guest.bin'], 'guest-binary', 60)
            symbols = run([tools['nm'], '-n', out / 'guest.elf'], 'guest-symbols', 60)
            record['guest_symbols'] = {name: int(address, 16) for address, _, name in re.findall(
                r'^([0-9a-fA-F]+)\s+(\w)\s+(\S+)$', symbols, re.M)}
            raw = (out / 'guest.bin').read_bytes()
            require(0 < len(raw) <= 2048 and len(raw) % 4 == 0, 'guest exceeds fixed ROM section')
            raw = raw.ljust(131072, b'\0')
            words = [int.from_bytes(raw[n:n + 4], 'little') for n in range(0, len(raw), 4)]
            banks = [out / ('bank%d.hex' % i) for i in range(2)]
            for index, path in enumerate(banks):
                path.write_text(''.join('%08x\n' % word for word in words[index::2]))
            record['first_words'] = words[:2]
            run([tools['mill'], '-i', 'IonSoC.test.runMain', 'platform.CommonA1DynamicMain', out / 'rtl', *banks,
                '--experimental-a1-profile=' + PROFILE, '--compile-receipt=' + str(compile_receipt)], 'emit-runtime', 600)
            value = check_identity(json.loads((out / 'rtl/microarchitecture-identity.json').read_text()), PROFILE, True)
            static = old['structures'][PROFILE]['identity']
            for key in ('effectiveConfig', 'effectiveCore', 'memoryProfile', 'sharedFabricConfig'):
                require(value[key] == static[key], 'runtime/static selected CPU or shared fabric differs: ' + key)
            require(value['identitySha256'] != static['identitySha256'], 'runtime context was not bound into identity')
            record['identity'] = value
            rtl = sorted((out / 'rtl').glob('*.sv'))
            require(rtl, 'runtime emitter produced no real SV')
            definitions = ['-g2012', '-DSTOP_COND=1', '-DASSERT_VERBOSE_COND=1', '-DENABLE_INITIAL_MEM_=1']
            run([tools['iverilog'], *definitions, '-E', '-o', out / 'preprocessed.sv', *rtl], 'preprocess', 180)
            original = (out / 'preprocessed.sv').read_text()
            reads = re.findall(r'\$readmemh\s*\(\s*"([^"]+)"', original)
            require(reads == [str(p) for p in banks] and original.count('$fatal') > 0, 'ROM or production assertion binding missing')
            required_instances = ('CommonA1CpuTile', 'CommonA1RuntimePark', 'CommonMachineFabric',
                'CompletedCanonicalStoreForwarding', 'BranchResolutionMailbox', 'CircularFetchInstructionStorage',
                'MixedCoherentLineHome', 'CommonRuntimeEpochBoundary', 'CommonNetworkRuntimeSequencer',
                'CommonDebugRuntimeSequencer', 'CommonFixedMacRuntimeAdapter', 'Axi4ClockDomainBoundary')
            for module in required_instances:
                require(re.search(r'\b' + module + r'\s+\w+\s*\(', original) is not None,
                        'missing actual runtime SV instance: ' + module)
            record['runtime_instance_witnesses'] = list(required_instances)
            lowered = run([tools['sv2v'], '--exclude=SeverityTask', out / 'preprocessed.sv'], 'lower', 180)
            for token in ('$fatal', '$error'):
                require(original.count(token) == lowered.count(token), 'severity lost during conversion: ' + token)
            record['severity_counts'] = {token: lowered.count(token) for token in ('$fatal', '$error')}
            (out / 'lowered.v').write_text(lowered)
            back = [ROOT / 'fpga/common/dynamic' / (name + '.sv') for name in
                ('behavioral_primitives', 'native_clock_gate', 'native_clock_drp', 'native_dynamic_clock_domain')]
            run([tools['iverilog'], *definitions, '-s', 'dynamic_roundtrip_tb', '-o', out / 'test.vvp',
                out / 'lowered.v', *back, ROOT / 'simulator/cdc/rtl8211f_pin_model.sv',
                HERE / 'a1_experimental_soc_tb.sv'], 'compile-native', 180)
            record['model'] = str(out / 'test.vvp')
            record['status'] = 'PASS_REAL_PLATFORM_MODEL_BUILD'
        else:
            old = previous('PASS_REAL_PLATFORM_MODEL_BUILD')
            value = check_identity(old['identity'], PROFILE, True)
            identity.check_reuse(value, json.loads((Path(old['model']).parent / 'rtl/microarchitecture-identity.json').read_text()))
            record['identity'] = value
            symbols, first = old['guest_symbols'], old['first_words']
            command = [tools['vvp'], '-i', old['model'], '+done_pc=%x' % symbols['guest_done'],
                '+fail_pc=%x' % symbols['guest_fail'], '+rom0_first=%x' % first[0], '+rom1_first=%x' % first[1], '+telemetry_smoke']
            log = run(command, 'smoke', 300)
            require(log.count('TELEMETRY_SMOKE_PASS') == 1 and 'EXPERIMENTAL_SOC_NEGATIVE_REACHED' not in log,
                    'missing unique positive independent guest oracle')
            code, log = base.run(command + ['+wrong_ddr_data'], out, 'wrong-ddr-data', 300, record)
            require(code == 1 and log.count('EXPERIMENTAL_SOC_NEGATIVE_REACHED') == 1 and
                    log.count('ROUNDTRIP_GUEST_FAIL_PC') == 1 and 'TELEMETRY_SMOKE_PASS' not in log and
                    'NEGATIVE_ESCAPED' not in log, 'negative did not reach actual DDR handshake and unchanged guest failure oracle')
            record['negative_scope'] = 'actual manager input mutation, first DDR line first accepted data beat XOR1; not RTL mutation'
            record['model_artifacts'] = old['artifacts']
            verify_files(old['artifacts'])
            record['status'] = 'PASS_EXPERIMENTAL_A1_SOC_BOUNDED_SMOKE'
        require(source_hashes() == record['source_sha256'], 'source drift during acceptance')
        require(subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip() == record['source_commit'],
                'HEAD changed during acceptance')
        verify_files(record['compile_receipt'])
        verify_compile_receipt(compile_receipt)
        require(tool_hashes(tools) == record['tools'], 'tool drift during acceptance')
        record['artifacts'] = file_map(p for p in out.rglob('*') if p.is_file() and p.name != 'receipt.json')
    except Exception as exc:
        record['status'] = 'FAIL'; record['error'] = str(exc)
        raise
    finally:
        record['artifacts'] = file_map(p for p in out.rglob('*') if p.is_file() and p.name != 'receipt.json')
        (out / 'receipt.json').write_text(json.dumps(record, indent=2) + '\n')


if __name__ == '__main__':
    main()
