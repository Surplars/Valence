#!/usr/bin/env python3
"""Scoped real-header syntax gate and content-bound generated-object reuse.

Only intercepts GSIM host/model C++ invocations in the explicitly launched
focused runner. Does not edit run.py, install tools, or reuse a prior DUT model.
Every model is freshly elaborated/generated by its owning runner. Subsequent
hosts may reuse exactly matching objects from that same generated directory.
"""
import hashlib
import json
import os
from pathlib import Path
import re
import runpy
import sys

import run as common


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def install():
    original = common.run
    def gated(command, **kwargs):
        command = [str(x) for x in command]
        cpp = [Path(x) for x in command if x.endswith('.cpp')]
        models = [p for p in cpp if re.search(r'Gsim[0-9]+\.cpp$', p.name)]
        if not models or '-o' not in command:
            return original(command, **kwargs)
        hosts = [p for p in cpp if p not in models]
        if len(hosts) != 1:
            raise RuntimeError('exactly one independent host required for real-header API gate')
        target = Path(command[command.index('-o') + 1])
        out = target.parent
        flags = [arg for i, arg in enumerate(command[1:])
                 if arg not in [str(p) for p in cpp] and arg != '-ldl' and arg != '-o'
                 and i != command[1:].index('-o') + 1]
        # The real generated header is already present. Reject missing/renamed
        # APIs before spending time compiling the large generated DUT sources.
        syntax_log = out / (target.name + '-header-syntax.log')
        original([command[0], *flags, '-fsyntax-only', hosts[0]],
                 log=syntax_log, timeout=180)
        header_inputs = {str(p): sha(p) for p in sorted(out.glob('*.h'))}
        receipt = {'schema': 'real-gsim-header-gate-v1', 'host': str(hosts[0]), 'host_sha256': sha(hosts[0]),
                   'headers': header_inputs, 'compiler': str(Path(command[0]).resolve()),
                   'flags': flags, 'syntax_pass': True, 'objects': []}
        objects = []
        for source in models + hosts:
            key = hashlib.sha256(json.dumps({'source': sha(source), 'headers': header_inputs,
                  'flags': flags, 'compiler': sha(command[0])}, sort_keys=True).encode()).hexdigest()
            obj = out / (source.stem + '-' + key[:16] + '.o')
            reused = obj.exists()
            if not reused:
                original([command[0], *flags, '-c', source, '-o', obj],
                         log=out / (obj.name + '.log'), timeout=600)
            receipt['objects'].append({'source': str(source), 'source_sha256': sha(source),
                'object': str(obj), 'object_sha256': sha(obj), 'key': key, 'reused': reused})
            objects.append(obj)
        original([command[0], *flags, *objects, '-ldl', '-o', target], **kwargs)
        receipt['binary_sha256'] = sha(target)
        (out / (target.name + '-compile-receipt.json')).write_text(json.dumps(receipt, indent=2) + '\n')
    common.run = gated


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit('usage: m2_r1_compile_gate.py focused_runner.py [args ...]')
    install()
    script = Path(sys.argv[1]).resolve(strict=True)
    sys.argv = [str(script), *sys.argv[2:]]
    runpy.run_path(str(script), run_name='__main__')
