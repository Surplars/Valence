/** Real LSU, including completion replacement; backpressure is deliberately legal here. */
class ProofControlCapacityGsim extends Module {
    val p = ThreeProofRowNativeProfile.config.coreParams
    val dut = Module(new ParallelLoadStoreUnit(p, canonicalHandoff = true,
        localTaggedResponseReady = p.localTaggedResponseReady, observeOrdinaryLoadCapacity = true))
    val io = IO(new Bundle {
        val start = Flipped(Decoupled(new MemoryOperation(p)))
        val memory = new DataPort(p.dataReturnHandleBits)
        val completeReady = Input(Bool())
        val completeValid = Output(Bool())
        val capacity = Output(Bool())
        val slot = Output(UInt(2.W))
        val actualSlot = Output(UInt(2.W))
        val live = Output(UInt(4.W))
    })
    dut.io.start <> io.start
    io.memory <> dut.io.memory
    dut.io.complete.ready := io.completeReady
    io.completeValid := dut.io.complete.valid
    dut.io.parallel := true.B
    dut.io.cancel := VecInit(Seq.fill(4)(false.B))
    dut.io.issueDestination.foreach(_ := 0.U.asTypeOf(Valid(UInt(p.physBits.W))))
    dut.io.relaxStoreOwner.foreach(_ := 0.U.asTypeOf(Valid(new RobToken(p))))
    dut.io.boundHeadStoreOverlapQualified.foreach(_ := false.B)
    dut.io.fastStoreRetire := false.B
    dut.io.fastLoadRetire := false.B
    io.capacity := dut.io.ordinaryLoadCapacity.get.available
    io.slot := dut.io.ordinaryLoadCapacity.get.slot
    io.actualSlot := dut.io.ordinaryLoadCapacity.get.actualSlot
    io.live := dut.io.live.asUInt
}

/** Actual three-row bank, with externally controlled registered-owner snapshots.
  * Collision switches alter stimulus only at the translated registered boundary;
  * no result or expected value is generated by a DUT authorization predicate.
  */
class ProofControlBankGsim extends Module {
    val p = ThreeProofRowNativeProfile.config.coreParams
    val bank = Module(new PendingVirtualStoreProof(p, true, true,
        checkBindPlanning = true, ownerStateCleanup = true))
    val io = IO(new Bundle {
        val storeMask = Input(UInt(16.W))
        val loadMask = Input(UInt(16.W))
        val overrideIndex = Input(UInt(4.W))
        val overrideTag = Input(UInt(64.W))
        val queryMask = Input(UInt(16.W))
        val bind = Input(UInt(3.W))
        val loadCandidate = Input(Bool())
        val loadIndex = Input(UInt(4.W))
        val loadAddress = Input(UInt(64.W))
        val stable = Input(Bool())
        val epoch = Input(UInt(32.W))
        val replyEpoch = Input(UInt(32.W))
        val replyValid = Input(Bool())
        val flush = Input(Bool())
        val dropOldOnIncoming = Input(Bool())
        val dropIncomingOwner = Input(Bool())
        val dropIndex = Input(UInt(4.W))
        val flushOnIncoming = Input(Bool())
        val oldNewCollision = Output(Bool())
        val staleIncoming = Output(Bool())
        val incoming = Output(Bool())
        val rawLoadValid = Output(Bool())
        val load = Output(Valid(new VirtualRamLoadCertificate(p)))
        val proof0 = Output(Valid(new MemoryAddressProof(p)))
        val proof1 = Output(Valid(new MemoryAddressProof(p)))
        val proof2 = Output(Valid(new MemoryAddressProof(p)))
        val bound = Output(UInt(3.W))
        val evict = Output(Bool())
        val unmaskedQuery = Output(UInt(16.W))
        val occupied = Output(UInt(3.W))
    })
    def tag(index: UInt): UInt = Mux(index === io.overrideIndex, io.overrideTag, index.pad(64) + 1.U)
    val translatedLoad = BoringUtils.bore(bank.translatedValid) && !BoringUtils.bore(bank.translatedStore)
    val translatedIndex = BoringUtils.bore(bank.translated.token.index)
    val oldValid = BoringUtils.bore(bank.loadValid)
    val oldIndex = BoringUtils.bore(bank.load.token.index)
    val drop = Mux(io.dropOldOnIncoming, UIntToOH(io.dropIndex, 16), 0.U) |
        Mux(io.dropIncomingOwner, UIntToOH(translatedIndex, 16), 0.U)
    val effectiveLoads = io.loadMask & ~Mux(translatedLoad, drop, 0.U)
    bank.io.currentPendingLoadMask.get := effectiveLoads
    bank.io.head := 0.U
    for (i <- 0 until 16) {
        bank.io.owners(i).valid := io.storeMask(i)
        bank.io.owners(i).bits.token.index := i.U
        bank.io.owners(i).bits.token.tag := tag(i.U)
        bank.io.owners(i).bits.address := (BigInt("80200000", 16) + 8 * i).U
        bank.io.owners(i).bits.size := 3.U
        bank.io.owners(i).bits.mask := 255.U
    }
    bank.io.queryEligible := io.queryMask
    bank.io.clearOwners := 0.U
    bank.io.consume := 0.U.asTypeOf(bank.io.consume)
    bank.io.bind := io.bind
    bank.io.pause := false.B
    bank.io.flushQueries := io.flush || (io.flushOnIncoming && translatedLoad)
    bank.io.loadCandidate.valid := io.loadCandidate
    bank.io.loadCandidate.bits.token.index := io.loadIndex
    bank.io.loadCandidate.bits.token.tag := tag(io.loadIndex)
    bank.io.loadCandidate.bits.address := io.loadAddress
    bank.io.loadCandidate.bits.size := 3.U
    bank.io.precheck.stable := io.stable
    bank.io.precheck.epoch := io.epoch
    bank.io.precheck.response.valid := io.replyValid
    bank.io.precheck.response.bits.physicalAddress := bank.io.precheck.request.bits.address + 4096.U
    bank.io.precheck.response.bits.pbmt := 0.U
    bank.io.precheck.response.bits.epoch := io.replyEpoch
    bank.io.pmpState := 0.U.asTypeOf(bank.io.pmpState)
    bank.io.privilege := 3.U
    io.incoming := translatedLoad
    io.oldNewCollision := translatedLoad && oldValid && oldIndex === io.dropIndex &&
        translatedIndex =/= oldIndex && !effectiveLoads(oldIndex)
    io.staleIncoming := translatedLoad && !effectiveLoads(translatedIndex)
    io.rawLoadValid := oldValid
    io.load := bank.io.loadPrepared
    io.proof0 := bank.io.proofs(0); io.proof1 := bank.io.proofs(1); io.proof2 := bank.io.proofs(2)
    io.bound := bank.io.bound
    io.evict := BoringUtils.bore(bank.evict)
    io.unmaskedQuery := BoringUtils.bore(bank.queryMask)
    io.occupied := VecInit(bank.state.map(s => BoringUtils.bore(s) =/= 0.U)).asUInt
}

object ProofControlComponentsMain extends App {
    require(args.length == 2)
    if (args(1) == "bank") ChiselStage.emitCHIRRTLFile(new ProofControlBankGsim, Array("--target-dir", args(0)))
    else if (args(1) == "capacity")
        ChiselStage.emitCHIRRTLFile(new ProofControlCapacityGsim, Array("--target-dir", args(0)))
    else throw new IllegalArgumentException("bank|capacity")
}
